import { test, expect } from '@playwright/test'
import { mockApi, login } from './helpers.mjs'

async function confirm(page, newRecord = false) {
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: newRecord ? 'Revisar alta' : 'Revisar cambios', exact: true }).click()
  await dialog.getByRole('button', { name: 'Confirmar y guardar', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByText('Catálogo guardado.', { exact: false })).toBeVisible()
}

test('ABM móvil: categoría, producto, modificación, archivo y restauración', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  const state = await mockApi(page)
  await login(page)
  await page.getByRole('button', { name: 'Nueva categoría', exact: true }).click()
  let form = page.getByRole('dialog')
  await form.getByLabel('Nombre', { exact: true }).fill('Postres')
  await form.getByLabel('Orden de aparición').fill('1')
  expect(state.categories.some(c => c.name === 'Postres')).toBe(false)
  await confirm(page, true)

  await page.getByRole('button', { name: 'Nuevo producto', exact: true }).click()
  form = page.getByRole('dialog')
  await form.getByLabel('Nombre', { exact: true }).fill('Flan casero')
  await form.getByLabel('Categoría del producto').selectOption({ label: 'Postres' })
  await form.getByLabel('Precio ($)', { exact: true }).fill('4500')
  await confirm(page, true)
  await expect(page.getByLabel('Cambiar foto de Flan casero')).toBeVisible()
  const id = state.products.find(p => p.name === 'Flan casero').id
  expect(state.prices.find(p => p.id === id).price).toBe(4500)

  await page.getByRole('button', { name: 'Editar producto Flan casero', exact: true }).click()
  form = page.getByRole('dialog')
  await form.getByLabel('Nombre', { exact: true }).fill('Flan con dulce')
  await form.getByLabel('Precio ($)', { exact: true }).fill('5000')
  await form.getByLabel('Categoría del producto').selectOption({ label: 'Empanadas' })
  await confirm(page)
  await page.goto('/')
  await page.getByRole('button').filter({ has: page.getByRole('heading', { name: 'Empanadas', exact: true }) }).click()
  await expect(page.getByRole('heading', { name: 'Flan con dulce', exact: true })).toBeVisible()
  await expect(page.getByText('$5000', { exact: true })).toBeVisible()

  await page.goto('/#/admin')
  await page.getByLabel('Buscar producto').fill('Flan con dulce')
  await page.getByRole('button', { name: 'Editar producto Flan con dulce', exact: true }).click()
  await page.getByRole('dialog').getByLabel('Archivado (oculto en el menú)').check()
  await confirm(page)
  expect(state.products.find(p => p.id === id).archived).toBe(true)
  await page.goto('/')
  await page.getByRole('button').filter({ has: page.getByRole('heading', { name: 'Empanadas', exact: true }) }).click()
  await expect(page.getByRole('heading', { name: 'Flan con dulce', exact: true })).toHaveCount(0)

  await page.goto('/#/admin')
  await page.getByLabel('Mostrar también productos archivados').check()
  await page.getByLabel('Buscar producto').fill('Flan con dulce')
  await page.getByRole('button', { name: 'Editar producto Flan con dulce', exact: true }).click()
  await page.getByRole('dialog').getByLabel('Archivado (oculto en el menú)').uncheck()
  await confirm(page)
  expect(state.products.find(p => p.id === id).archived).toBe(false)

  await page.getByText('Administrar categorías', { exact: true }).click()
  await page.getByRole('button', { name: 'Editar categoría Postres', exact: true }).click()
  form = page.getByRole('dialog')
  await form.getByLabel('Nombre', { exact: true }).fill('Dulces')
  await form.getByLabel('Archivado (oculto en el menú)').check()
  await confirm(page)
  expect(state.categories.find(c => c.name === 'Dulces').archived).toBe(true)
  await page.getByRole('button', { name: 'Editar categoría Dulces', exact: true }).click()
  await page.getByRole('dialog').getByLabel('Archivado (oculto en el menú)').uncheck()
  await confirm(page)
  expect(state.categories.find(c => c.name === 'Dulces').archived).toBe(false)
})

test('ABM: no archiva categorías con productos ni sobrescribe conflictos', async ({ page }) => {
  const state = await mockApi(page)
  await login(page)
  await page.getByText('Administrar categorías', { exact: true }).click()
  await page.getByRole('button', { name: 'Editar categoría Empanadas', exact: true }).click()
  const form = page.getByRole('dialog')
  await form.getByLabel('Archivado (oculto en el menú)').check()
  await form.getByRole('button', { name: 'Revisar cambios', exact: true }).click()
  await form.getByRole('button', { name: 'Confirmar y guardar', exact: true }).click()
  await expect(form.getByRole('alert')).toContainText('todavía tiene productos visibles')
  page.on('dialog', d => d.accept())
  await form.getByRole('button', { name: 'Cancelar', exact: true }).click()
  state.catalogConflict = true
  await page.getByRole('button', { name: 'Editar producto Hamburguesa', exact: true }).click()
  await form.getByLabel('Nombre', { exact: true }).fill('Hamburguesa nueva')
  await form.getByRole('button', { name: 'Revisar cambios', exact: true }).click()
  await form.getByRole('button', { name: 'Confirmar y guardar', exact: true }).click()
  await expect(form.getByRole('alert')).toContainText('Otro administrador modificó')
  expect(state.products.find(p => p.id === 1).name).toBe('Hamburguesa')
})

test('menú: producto archivado sale del carrito y un catálogo vacío se muestra correctamente', async ({ page }) => {
  const state = await mockApi(page)
  await page.goto('/')
  await page.getByRole('button').filter({ has: page.getByRole('heading', { name: 'Empanadas', exact: true }) }).click()
  await page.getByRole('button', { name: 'Agregar', exact: true }).first().click()
  await page.getByLabel('Nombre:', { exact: true }).fill('Cliente')
  state.products.find(p => p.id === 3).archived = true
  await page.getByRole('button', { name: 'Enviar por WhatsApp' }).click()
  await expect(page.getByText(/Quitamos productos que ya no están disponibles/)).toBeVisible()
  await expect(page.getByText('No agregaste productos aún.')).toBeVisible()
  expect(page.url()).toContain('127.0.0.1')
  state.products.forEach(p => { p.archived = true })
  await page.reload()
  await expect(page.getByText(/Por el momento no hay productos disponibles/)).toBeVisible()
})
